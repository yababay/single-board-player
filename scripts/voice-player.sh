#!/usr/bin/env bash

# Считываем поисковую фразу пользователя
USER_QUERY="$1"
if [ -z "$USER_QUERY" ]; then
    echo "Использование: $0 \"запрос на естественном языке\""
    exit 1
fi

# 1. Запускаем ваш отлаженный скрипт облачного ИИ-поиска
# Он возвращает строго "номер_плейлиста;номер_трека" (например, "1057;14")
echo "Распознавание смысла запроса через Яндекс..." >&2
AI_COMMAND=$( $(dirname "$0")/assistant.sh "$USER_QUERY" )

# Проверяем, вернул ли скрипт поиска валидную команду
if [[ ! "$AI_COMMAND" =~ ^[0-9]+\;[0-9]+$ ]]; then
    echo "Ошибка: Не удалось получить техническую команду от облачного ассистента." >&2
    exit 1
fi

# 2. Разбиваем полученную пару чисел на две независимые переменные
PLAYLIST_NUMBER="${AI_COMMAND%%;*}"
TRACK_NUMBER="${AI_COMMAND#*;}"

echo "ИИ выбрал Плейлист: $PLAYLIST_NUMBER, Трек: $TRACK_NUMBER" >&2

# 3. Элегантное форматирование четырехзначного номера с лидирующими нулями.
# %04d автоматически превратит "57" в "0057", а "1057" оставит как "1057".
FORMATED_NUM=$(printf "%04d" "$PLAYLIST_NUMBER")

# 4. Ищем точное имя плейлиста в mpd. 
# Якорь "^" гарантирует, что поиск идет строго с начала строки. 
# Шаблон "^0057-" никогда не совпадет со строкой "1057-".
PLAYLIST_NAME=$(mpc lsplaylists | grep -E "^${FORMATED_NUM}-" | head -n 1)

if [ -z "$PLAYLIST_NAME" ]; then
    echo "Ошибка: Плейлист под номером ${FORMATED_NUM} не найден в базе MPD." >&2
    exit 1
fi

# 5. Исполняем физические команды управления проигрывателем mpc
echo "Запуск воспроизведения: $PLAYLIST_NAME -> Трек №$TRACK_NUMBER" >&2

mpc clear                                 # Очищаем текущую очередь воспроизведения
mpc load "$PLAYLIST_NAME"                 # Загружаем найденный плейлист
mpc play "$TRACK_NUMBER"                  # Включаем нужную композицию

