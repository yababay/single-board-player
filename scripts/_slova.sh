USER_TEXT=$1

# Переводим в нижний регистр и убираем мусорные глаголы управления
USER_TEXT=$(echo "$USER_TEXT" | tr '[:upper:]' '[:lower:]')
USER_TEXT=$(echo "$USER_TEXT" | sed -E 's/^(найди|включи|поставь|вруби|запусти|слушаю|хочу_послушать)[[:space:]]*//g')

echo "Очищенный запрос для ИИ: \"$USER_TEXT\"" >&2
